/// Display name for [alpha2] in the requested language.
/// Falls back to the pattern name, then the code itself.
String countryDisplayName(String alpha2, {required bool chinese}) {
  final code = alpha2.trim().toUpperCase();
  final localized = chinese ? kCountryNameZh[code] : kCountryNameEn[code];
  return localized ?? kCountries[code]?.name ?? code;
}
